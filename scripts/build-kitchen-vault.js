/**
 * Rebuild kitchen/vault.js from kitchen/kitchen-config.js (gitignored).
 *
 * Usage:
 *   node scripts/build-kitchen-vault.js
 *
 * Requires kitchen/kitchen-config.js with:
 *   window.BB_KITCHEN = { users: [{email, password}], portalKey, scriptUrl }
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const cfgPath = path.join(root, 'kitchen', 'kitchen-config.js');
const outPath = path.join(root, 'kitchen', 'vault.js');

if (!fs.existsSync(cfgPath)) {
  console.error('Missing', cfgPath);
  console.error('Copy kitchen-config.example.js -> kitchen/kitchen-config.js and fill secrets.');
  process.exit(1);
}

// Evaluate config in a sandbox-ish way
const code = fs.readFileSync(cfgPath, 'utf8');
const sandbox = { window: {} };
// eslint-disable-next-line no-new-func
Function('window', code)(sandbox.window);
const cfg = sandbox.window.BB_KITCHEN;
if (!cfg || !cfg.portalKey || !cfg.scriptUrl) {
  console.error('kitchen-config.js must define portalKey and scriptUrl');
  process.exit(1);
}

let users = [];
if (cfg.users && cfg.users.length) {
  users = cfg.users;
} else if (cfg.email && cfg.password) {
  users = [{ email: cfg.email, password: cfg.password }];
}
if (!users.length) {
  console.error('No users in kitchen-config.js');
  process.exit(1);
}

const plaintext = Buffer.from(
  JSON.stringify({ portalKey: cfg.portalKey, scriptUrl: cfg.scriptUrl }),
  'utf8'
);

function seal(email, password) {
  const salt = crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const key = crypto.pbkdf2Sync(password, salt, 120000, 32, 'sha256');
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  cipher.setAAD(Buffer.from(String(email).toLowerCase(), 'utf8'));
  const enc = Buffer.concat([cipher.update(plaintext), cipher.final()]);
  const tag = cipher.getAuthTag();
  return {
    email: String(email).toLowerCase(),
    salt: salt.toString('base64'),
    iv: iv.toString('base64'),
    tag: tag.toString('base64'),
    data: enc.toString('base64'),
  };
}

const vault = {
  v: 1,
  app: 'bobs-kitchen',
  users: users.map((u) => seal(u.email, u.password)),
};

const out =
  '/* Auto-generated by scripts/build-kitchen-vault.js — safe to host on GitHub Pages.\n' +
  ' * Portal key is encrypted per staff password. Rebuild after changing passwords.\n' +
  ' */\n' +
  'window.BB_KITCHEN_VAULT = ' +
  JSON.stringify(vault, null, 2) +
  ';\n';

fs.writeFileSync(outPath, out, 'utf8');
console.log('Wrote', outPath, 'for', vault.users.length, 'user(s)');
